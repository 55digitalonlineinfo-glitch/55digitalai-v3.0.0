#!/usr/bin/env python3
"""
55DigitalAI — Scaffold a Client's Scheduled Negative-Keyword Audit
=============================================================
Purpose  : Generates clients/<slug>/scripts/run_audit.sh — the unattended
           Tue/Fri launchd audit script — for a client, using proven
           locking/guard/dashboard-rebuild boilerplate, with the AI-judgment
           prompt derived generically from
           clients/<slug>/client-brief.md's standard sections (Business
           Context, Products/Services, Brand Terms, Geography, Always
           Negate, Protected) instead of hand-written bespoke prose.

           Because the prompt is auto-generated rather than hand-tuned, it
           only knows what client-brief.md says — if the brief is thin,
           the audit's judgment will be too. Review the generated
           run_audit.sh once before relying on it, same as you'd review any
           new client's first live run.

Prereqs  : clients.json must have this slug with a customer_id AND a
           negative_list_id already set (run negative_keyword_audit.py
           list-lists/set-list/create-list first if not). client-brief.md
           must exist for this client.

Usage    : python3 scripts/scaffold_client_audit.py <slug> [--force]
                   [--weekdays tue,fri] [--lookback-days 4]
           Then: python3 scripts/setup_launchd.py --only <slug>
           Test:  AUDIT_FORCE=1 bash clients/<slug>/scripts/run_audit.sh
Changelog: 2026-07-26  Initial version, generalized from an earlier
                       hand-written run_audit.sh
           2026-07-26  --weekdays / --lookback-days made configurable
                       instead of hardcoded Tue/Fri + 4 days
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from client_registry import resolve  # noqa: E402

WORKSPACE = Path(__file__).resolve().parent.parent

WEEKDAY_NUMBERS = {"mon": 1, "tue": 2, "wed": 3, "thu": 4, "fri": 5, "sat": 6, "sun": 7}
WEEKDAY_NAMES = {v: k.capitalize() for k, v in WEEKDAY_NUMBERS.items()}


def parse_weekdays(raw: str) -> list:
    """Accepts 'tue,fri' or 'tuesday, Friday' etc. Returns sorted launchd-style
    day numbers (1=Mon...7=Sun, matching `date +%u`)."""
    days = []
    for part in raw.split(","):
        key = part.strip()[:3].lower()
        if key not in WEEKDAY_NUMBERS:
            raise ValueError(f"'{part.strip()}' isn't a day of the week (use mon/tue/wed/thu/fri/sat/sun)")
        days.append(WEEKDAY_NUMBERS[key])
    if not days:
        raise ValueError("--weekdays can't be empty")
    return sorted(set(days))


TEMPLATE = '''#!/bin/bash
# {name} ({domain}) — negative keyword audit (local launchd).
# Runs every {weekday_names}, every 30 min 09:00-22:00 Warsaw via launchd.
# Looks back {lookback_days} day(s) of search terms each run.
# Stops retrying once "Audit finished successfully" appears in today's log.
# Uses Claude CLI (Pro subscription) for AI analysis.
# Rebuilds the dashboard once the attempt finishes (success, timeout, or failure).
# To run manually: bash clients/{slug}/scripts/run_audit.sh (from anywhere, or via its full path)
#
# Auto-generated by scripts/scaffold_client_audit.py from client-brief.md —
# review the prompt below once before trusting it on a live account.

# Windows Task Scheduler launches processes with a minimal PATH (basically just
# System32) and Git Bash doesn't self-source its usual PATH additions unless
# invoked as a login shell — so every coreutil below (dirname/mkdir/grep/date/
# stat/etc.) fails with "command not found" (exit 127) the instant this fires
# unattended via Task Scheduler, even though it works fine run by hand from a
# normal shell. This MUST run before anything else, including WORKSPACE below,
# since that line itself calls dirname. No-op on macOS/Linux (dirs don't exist).
for _gitbin in "/c/Program Files/Git/usr/bin" "/c/Program Files/Git/bin" \
               "$HOME/AppData/Local/Programs/Git/usr/bin" "$HOME/AppData/Local/Programs/Git/bin"; do
    [[ -d "$_gitbin" ]] && PATH="$_gitbin:$PATH"
done

WORKSPACE="$(cd "$(dirname "${{BASH_SOURCE[0]}}")/../../.." && pwd)"
CLIENT_DIR="$WORKSPACE/clients/{slug}"
LOG="$CLIENT_DIR/reports/keywords_audit_$(date +%Y-%m-%d).log"
TIMEOUT_MIN=25

mkdir -p "$CLIENT_DIR/reports"
cd "$WORKSPACE"

# Stop retrying once today's run already succeeded
if grep -q "=== Audit finished successfully" "$LOG" 2>/dev/null; then
    exit 0
fi

# Guard: only run inside the intended {weekday_names} 09:00-22:00 Warsaw window.
# launchd replays missed StartCalendarInterval jobs the moment the Mac wakes from
# sleep, ignoring the hour/day filter — this caused all 9 clients' overnight catch-up
# runs to fire at once on 2026-07-10/11 and exhaust the Claude Pro session limit
# (see the primary-Mac incident this guard was added for).
# Set AUDIT_FORCE=1 to bypass this guard for manual/ad-hoc runs.
if [[ "${{AUDIT_FORCE:-0}}" != "1" ]]; then
    DOW=$(TZ="Europe/Warsaw" date +%u)   # 1=Mon ... 5=Fri ... 7=Sun
    HOUR=$(TZ="Europe/Warsaw" date +%H)
    case "$DOW" in
        {weekday_case_pattern}) ;;
        *) exit 0 ;;
    esac
    if (( 10#$HOUR < 9 || 10#$HOUR >= 22 )); then
        exit 0
    fi
fi

# Workspace-wide lock: only one client's Claude session runs at a time.
# All clients share the same 30-min launchd slots, so without this they collide
# and blow through the Claude Pro session limit together.
LOCKDIR="/tmp/ppc-workspace-claude-audit.lock"
LOCK_WAITED=0
LOCK_TIMEOUT=1200
while ! mkdir "$LOCKDIR" 2>/dev/null; do
    if [[ -d "$LOCKDIR" ]]; then
        LOCK_AGE=$(( $(date +%s) - $(stat -c %Y "$LOCKDIR" 2>/dev/null || stat -f %m "$LOCKDIR" 2>/dev/null || echo 0) ))
        if [[ $LOCK_AGE -gt 1800 ]]; then
            rm -rf "$LOCKDIR"
            continue
        fi
    fi
    sleep 10
    LOCK_WAITED=$((LOCK_WAITED + 10))
    if [[ $LOCK_WAITED -ge $LOCK_TIMEOUT ]]; then
        echo "$(date '+%Y-%m-%d %H:%M:%S') [SKIP] Could not acquire workspace lock after ${{LOCK_TIMEOUT}}s — another client is running" >> "$LOG"
        exit 0
    fi
done
trap 'rmdir "$LOCKDIR" 2>/dev/null' EXIT

# Find timeout command: GNU coreutils (gtimeout) or Linux timeout; skip on macOS without coreutils
TIMEOUT_CMD=$(command -v gtimeout 2>/dev/null || command -v timeout 2>/dev/null || echo "")

# Find Claude binary: prefer PATH, fall back to the native installer's default location
CLAUDE=$(command -v claude 2>/dev/null)
if [[ -z "$CLAUDE" ]]; then
    CLAUDE="$HOME/.local/bin/claude"
fi
if [[ ! -x "$CLAUDE" ]]; then
    echo "$(date '+%Y-%m-%d %H:%M:%S') [ERROR] Claude binary not found" >> "$LOG"
    exit 1
fi

echo "" >> "$LOG"
echo "════════════════════════════════════════" >> "$LOG"
echo "  Attempt: $(date '+%Y-%m-%d %H:%M:%S')" >> "$LOG"
echo "════════════════════════════════════════" >> "$LOG"

${{TIMEOUT_CMD:+$TIMEOUT_CMD "${{TIMEOUT_MIN}}m"}} "$CLAUDE" \\
  --add-dir "$WORKSPACE" \\
  --dangerously-skip-permissions \\
  -p "You are running as the automated, unattended {weekday_names} scheduled negative-keyword audit for this account — not an interactive manual /keyword-audit run. This account's own convention explicitly pre-approves this scheduled context to write directly to the shared negative list without pausing for approval; the manual-approval-required guard applies only to interactive runs, not to this one. Proceed straight to applying confirmed negatives via the apply step (add_shared_negatives.py ... --confirm) — do not stop to ask for confirmation.

You are a senior PPC specialist running a scheduled negative keyword audit for {name} ({domain}).

Read the client brief at clients/{slug}/client-brief.md before doing anything else — it is the single source of truth for this business. Apply its sections exactly: never negate anything listed under Products/Services Offered or Brand Terms; respect its Geography and Languages sections when judging whether a search term is in-scope; treat its Always Negate categories as pre-approved exclusion patterns; and never negate anything listed under Protected, even if another rule would suggest it.

Then run this Python using $WORKSPACE/.venv/bin/python3 to pull data:

from google.ads.googleads.client import GoogleAdsClient
from datetime import datetime, timedelta

client = GoogleAdsClient.load_from_storage('google-ads.yaml')
ga = client.get_service('GoogleAdsService')
today = datetime.utcnow().date()
date_from = str(today - timedelta(days={lookback_days}))
date_to = str(today)

rows = []
for r in ga.search(customer_id='{customer_id}', query=f'SELECT search_term_view.search_term, metrics.impressions, metrics.clicks, metrics.cost_micros, metrics.conversions FROM search_term_view WHERE segments.date BETWEEN \\"{{date_from}}\\" AND \\"{{date_to}}\\" AND metrics.impressions >= 1 ORDER BY metrics.cost_micros DESC LIMIT 2000'):
    rows.append({{'term': r.search_term_view.search_term, 'impressions': r.metrics.impressions, 'cost': round(r.metrics.cost_micros/1_000_000, 2), 'conversions': r.metrics.conversions}})

print(f'Terms: {{len(rows)}}')
for r in rows: print(f\\"{{r['cost']:.2f}}|{{r['impressions']}}i|{{r['conversions']:.0f}}cv|{{r['term']}}\\")

Using the data and client brief rules, analyse each term with AI judgment.

Add confirmed irrelevant terms as EXACT match negatives to shared set {negative_list_id} ({name} Negative Keyword List).

After compiling the NEGATED list, check it for a recurring pattern: a specific competitor brand name or unavailable/discontinued model name that appears in 2 or more of this run's exact-match negatives. For each such recurring token, add it as a BROAD match negative (the bare word/phrase, no brackets or quotes) to the same shared set, so future variations get blocked automatically instead of needing a fresh exact-match entry every time. Only do this for the specific brand/model token itself — never for a generic category, service, or geography word even if it recurs, since that could block legitimate searches for the client's own offering. Skip any candidate that overlaps with a brand/model/protected term in the client brief.

Print the following sections in order:
1. NEGATED — a complete numbered list of every term added this run, one per line in format: [NEGATED] term | reason (2 words max)
2. KEPT (borderline) — terms you decided to keep with explanation: [KEPT] term | reason
3. BROAD MATCH ADDITIONS — recurring competitor brand or unavailable-model tokens added as broad match negatives this run, one per line in format: [BROAD] token | appeared in N exact-match terms above (write \\"(none this run)\\" if nothing recurred)
4. SUMMARY — totals: terms reviewed, negated this run, kept, broad match additions.

Do NOT write any files. Print everything to stdout only." \\
  >> "$LOG" 2>&1

EXIT=$?

if [[ $EXIT -eq 0 ]]; then
    echo "" >> "$LOG"
    echo "=== Audit finished successfully at $(date) ===" >> "$LOG"
elif [[ $EXIT -eq 124 ]]; then
    echo "" >> "$LOG"
    echo "=== Audit TIMED OUT after ${{TIMEOUT_MIN}}m at $(date) ===" >> "$LOG"
else
    echo "" >> "$LOG"
    echo "=== Audit FAILED (exit $EXIT) at $(date) ===" >> "$LOG"
fi

# Refresh the dashboard so the new report/status shows up right away, not just on the hourly rebuild.
bash "$WORKSPACE/scripts/run_dashboard_build.sh"
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("slug")
    parser.add_argument("--force", action="store_true", help="Overwrite an existing run_audit.sh for this client")
    parser.add_argument("--weekdays", default="tue,fri",
                         help="Comma-separated days to run on, e.g. 'tue,fri' or 'mon,wed,fri' (default: tue,fri)")
    parser.add_argument("--lookback-days", type=int, default=4,
                         help="How many days of search terms to pull each run (default: 4)")
    args = parser.parse_args()

    try:
        weekday_numbers = parse_weekdays(args.weekdays)
    except ValueError as e:
        print(f"--weekdays error: {e}")
        sys.exit(1)

    if args.lookback_days < 1:
        print("--lookback-days must be at least 1")
        sys.exit(1)

    client = resolve(args.slug)
    if client is None:
        print(f"No entry for '{args.slug}' in clients.json — add it first.")
        sys.exit(1)

    if not client.get("negative_list_id"):
        print(f"clients.json has no negative_list_id for '{args.slug}' yet.")
        print(f"Run this first: python3 scripts/negative_keyword_audit.py list-lists {args.slug}")
        print("(then set-list or create-list to attach one).")
        sys.exit(1)

    brief_path = WORKSPACE / "clients" / args.slug / "client-brief.md"
    if not brief_path.exists():
        print(f"Missing {brief_path}")
        print(f"Copy clients/_template/client-brief.md to it and fill it in first.")
        sys.exit(1)

    out_path = WORKSPACE / "clients" / args.slug / "scripts" / "run_audit.sh"
    if out_path.exists() and not args.force:
        print(f"{out_path} already exists — pass --force to overwrite.")
        sys.exit(1)

    weekday_names = "/".join(WEEKDAY_NAMES[n] for n in weekday_numbers)
    weekday_case_pattern = "|".join(str(n) for n in weekday_numbers)

    script = TEMPLATE.format(
        name=client.get("name", args.slug),
        domain=client.get("domain", ""),
        slug=args.slug,
        customer_id=client["customer_id"],
        negative_list_id=client["negative_list_id"],
        weekday_names=weekday_names,
        weekday_case_pattern=weekday_case_pattern,
        lookback_days=args.lookback_days,
    )

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(script, encoding="utf-8")
    out_path.chmod(0o755)

    print(f"Wrote {out_path}")
    print(f"Schedule: {weekday_names}, 09:00-22:00 Warsaw, looking back {args.lookback_days} day(s) each run.")
    print()
    print("Review the generated prompt once, especially against client-brief.md's")
    print("Always Negate / Protected sections, before trusting it on a live account.")
    print()
    print("Next steps:")
    print(f"  1. Test:    AUDIT_FORCE=1 bash clients/{args.slug}/scripts/run_audit.sh")
    print(f"  2. Install: python3 scripts/setup_launchd.py --only {args.slug}")


if __name__ == "__main__":
    main()
