#!/usr/bin/env python3
"""
55DigitalAI — Scaffold a Client's Scheduled PMax Brand/Generic Search-Term Audit
=============================================================
Purpose  : Generates clients/<slug>/scripts/run_pmax_brand_generic_audit.sh —
           the unattended launchd version of /55-pmax-brand-generic-audit —
           same proven locking/guard/dashboard-rebuild boilerplate as
           scaffold_pmax_audit.py's run_pmax_audit.sh.

           Unlike scaffold_pmax_audit.py (which embeds a full hand-built AI
           prompt in the generated script, because pmax_audit.py is fetch-only
           and expects the outer Claude Code session to do the judgment),
           pmax_brand_generic_audit.py is already a self-contained
           fetch/analyze/apply orchestrator that shells out to `claude`
           itself for the analyze phase. So the generated script here is a
           thin wrapper: it just invokes that orchestrator directly with
           --confirm, inside the same guard/lock/timeout scaffolding every
           other scheduled audit in this toolkit uses.

           Writes branded-campaign negatives to client_registry.py's
           "pmax_branded_generic_list_id" and generic-campaign negatives to
           "negative_list_id" — same split /55-pmax-brand-generic-audit does
           interactively.

Prereqs  : clients.json must have this slug with a customer_id AND a
           negative_list_id already set. If the client has any ENABLED
           branded PMax campaign, pmax_branded_generic_list_id must also be
           set (run `pmax_brand_generic_audit.py <slug> --setup` once) and
           client-brief.md needs a "## Brand Terms" section. client-brief.md
           must exist either way.

Usage    : python3 scripts/scaffold_pmax_brand_generic_audit.py <slug> [--force]
                   [--weekdays tue,fri] [--lookback-days 4]
           Then: python3 scripts/setup_launchd.py --only <slug>-pmax-brand-generic-audit
           Test:  AUDIT_FORCE=1 bash clients/<slug>/scripts/run_pmax_brand_generic_audit.sh
Changelog: 2026-07-27  Initial version, adapted from scaffold_pmax_audit.py
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from client_registry import resolve  # noqa: E402

WORKSPACE = Path(__file__).resolve().parent.parent

WEEKDAY_NUMBERS = {"mon": 1, "tue": 2, "wed": 3, "thu": 4, "fri": 5, "sat": 6, "sun": 7}
WEEKDAY_NAMES = {v: k.capitalize() for k, v in WEEKDAY_NUMBERS.items()}


def parse_weekdays(raw: str) -> list:
    """Accepts 'tue,fri' or 'tuesday, Friday' etc. Returns sorted launchd-style
    day numbers (1=Mon...7=Sun, matching `date +%u`)."""
    days = []
    for part in raw.split(","):
        key = part.strip()[:3].lower()
        if key not in WEEKDAY_NUMBERS:
            raise ValueError(f"'{part.strip()}' isn't a day of the week (use mon/tue/wed/thu/fri/sat/sun)")
        days.append(WEEKDAY_NUMBERS[key])
    if not days:
        raise ValueError("--weekdays can't be empty")
    return sorted(set(days))


TEMPLATE = '''#!/bin/bash
# {name} ({domain}) — PMax brand/generic search-term audit (local launchd).
# Runs every {weekday_names}, every 30 min 09:00-22:00 Warsaw via launchd.
# Looks back {lookback_days} day(s) of PMax search terms each run.
# Stops retrying once "Audit finished successfully" appears in today's log.
# Delegates fetch/analyze/apply to pmax_brand_generic_audit.py --confirm,
# which shells out to the Claude CLI itself for the analyze phase (fork-safe,
# see that script's architecture note) — this wrapper only provides the same
# guard/lock/timeout/dashboard-rebuild scaffolding every other scheduled
# audit in this toolkit uses.
# To run manually: bash clients/{slug}/scripts/run_pmax_brand_generic_audit.sh (from anywhere, or via its full path)
#
# Auto-generated by scripts/scaffold_pmax_brand_generic_audit.py.

WORKSPACE="$(cd "$(dirname "${{BASH_SOURCE[0]}}")/../../.." && pwd)"
CLIENT_DIR="$WORKSPACE/clients/{slug}"
LOG="$CLIENT_DIR/reports/pmax_brand_generic_audit_$(date +%Y-%m-%d).log"
TIMEOUT_MIN=25

mkdir -p "$CLIENT_DIR/reports"
cd "$WORKSPACE"

# Stop retrying once today's run already succeeded
if grep -q "=== Audit finished successfully" "$LOG" 2>/dev/null; then
    exit 0
fi

# Guard: only run inside the intended {weekday_names} 09:00-22:00 Warsaw window.
# launchd replays missed StartCalendarInterval/interval jobs the moment the Mac
# wakes from sleep, ignoring the hour/day filter — this caused all 9 clients'
# overnight catch-up runs to fire at once on 2026-07-10/11 and exhaust the
# Claude Pro session limit (see the primary-Mac incident this guard was added
# for, same guard scaffold_pmax_audit.py and scaffold_client_audit.py use).
# Set AUDIT_FORCE=1 to bypass this guard for manual/ad-hoc runs.
if [[ "${{AUDIT_FORCE:-0}}" != "1" ]]; then
    DOW=$(TZ="Europe/Warsaw" date +%u)   # 1=Mon ... 5=Fri ... 7=Sun
    HOUR=$(TZ="Europe/Warsaw" date +%H)
    case "$DOW" in
        {weekday_case_pattern}) ;;
        *) exit 0 ;;
    esac
    if (( 10#$HOUR < 9 || 10#$HOUR >= 22 )); then
        exit 0
    fi
fi

# Workspace-wide lock: only one client's Claude session runs at a time.
# Shared with every other scheduled Claude-CLI audit (keyword-audit, plain
# PMax audit) across every client — they all serialize on this one lock, so
# they never collide and blow through the Claude Pro session limit together.
LOCKDIR="/tmp/ppc-workspace-claude-audit.lock"
LOCK_WAITED=0
LOCK_TIMEOUT=1200
while ! mkdir "$LOCKDIR" 2>/dev/null; do
    if [[ -d "$LOCKDIR" ]]; then
        LOCK_AGE=$(( $(date +%s) - $(stat -c %Y "$LOCKDIR" 2>/dev/null || stat -f %m "$LOCKDIR" 2>/dev/null || echo 0) ))
        if [[ $LOCK_AGE -gt 1800 ]]; then
            rm -rf "$LOCKDIR"
            continue
        fi
    fi
    sleep 10
    LOCK_WAITED=$((LOCK_WAITED + 10))
    if [[ $LOCK_WAITED -ge $LOCK_TIMEOUT ]]; then
        echo "$(date '+%Y-%m-%d %H:%M:%S') [SKIP] Could not acquire workspace lock after ${{LOCK_TIMEOUT}}s — another client is running" >> "$LOG"
        exit 0
    fi
done
trap 'rmdir "$LOCKDIR" 2>/dev/null' EXIT

# Find timeout command: GNU coreutils (gtimeout) or Linux timeout; skip on macOS without coreutils
TIMEOUT_CMD=$(command -v gtimeout 2>/dev/null || command -v timeout 2>/dev/null || echo "")

echo "" >> "$LOG"
echo "════════════════════════════════════════" >> "$LOG"
echo "  Attempt: $(date '+%Y-%m-%d %H:%M:%S')" >> "$LOG"
echo "════════════════════════════════════════" >> "$LOG"

${{TIMEOUT_CMD:+$TIMEOUT_CMD "${{TIMEOUT_MIN}}m"}} "$WORKSPACE/.venv/bin/python3" "$WORKSPACE/scripts/pmax_brand_generic_audit.py" {slug} --confirm --days {lookback_days} \\
  >> "$LOG" 2>&1

EXIT=$?

if [[ $EXIT -eq 0 ]]; then
    echo "" >> "$LOG"
    echo "=== Audit finished successfully at $(date) ===" >> "$LOG"
elif [[ $EXIT -eq 124 ]]; then
    echo "" >> "$LOG"
    echo "=== Audit TIMED OUT after ${{TIMEOUT_MIN}}m at $(date) ===" >> "$LOG"
else
    echo "" >> "$LOG"
    echo "=== Audit FAILED (exit $EXIT) at $(date) ===" >> "$LOG"
fi

# Refresh the dashboard so the new report/status shows up right away, not just on the hourly rebuild.
bash "$WORKSPACE/scripts/run_dashboard_build.sh"
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("slug")
    parser.add_argument("--force", action="store_true", help="Overwrite an existing run_pmax_brand_generic_audit.sh for this client")
    parser.add_argument("--weekdays", default="tue,fri",
                         help="Comma-separated days to run on, e.g. 'tue,fri' or 'mon,wed,fri' (default: tue,fri)")
    parser.add_argument("--lookback-days", type=int, default=4,
                         help="How many days of PMax search terms to pull each run (default: 4)")
    args = parser.parse_args()

    try:
        weekday_numbers = parse_weekdays(args.weekdays)
    except ValueError as e:
        print(f"--weekdays error: {e}")
        sys.exit(1)

    if args.lookback_days < 1:
        print("--lookback-days must be at least 1")
        sys.exit(1)

    client = resolve(args.slug)
    if client is None:
        print(f"No entry for '{args.slug}' in clients.json — add it first.")
        sys.exit(1)

    if not client.get("negative_list_id"):
        print(f"clients.json has no negative_list_id for '{args.slug}' yet.")
        print(f"Run this first: python3 scripts/negative_keyword_audit.py list-lists {args.slug}")
        print("(then set-list or create-list to attach one).")
        sys.exit(1)

    brief_path = WORKSPACE / "clients" / args.slug / "client-brief.md"
    if not brief_path.exists():
        print(f"Missing {brief_path}")
        print(f"Copy clients/_template/client-brief.md to it and fill it in first.")
        sys.exit(1)

    if not client.get("pmax_branded_generic_list_id"):
        print(f"NOTE: clients.json has no pmax_branded_generic_list_id for '{args.slug}' yet.")
        print("This is only required if the client has an ENABLED branded PMax campaign.")
        print(f"If it does, run this first: .venv/bin/python3 scripts/pmax_brand_generic_audit.py {args.slug} --setup")
        print("(otherwise the scheduled run will error on that campaign instead of writing anywhere.)")
        print()

    out_path = WORKSPACE / "clients" / args.slug / "scripts" / "run_pmax_brand_generic_audit.sh"
    if out_path.exists() and not args.force:
        print(f"{out_path} already exists — pass --force to overwrite.")
        sys.exit(1)

    weekday_names = "/".join(WEEKDAY_NAMES[n] for n in weekday_numbers)
    weekday_case_pattern = "|".join(str(n) for n in weekday_numbers)

    script = TEMPLATE.format(
        name=client.get("name", args.slug),
        domain=client.get("domain", ""),
        slug=args.slug,
        weekday_names=weekday_names,
        weekday_case_pattern=weekday_case_pattern,
        lookback_days=args.lookback_days,
    )

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(script, encoding="utf-8")
    out_path.chmod(0o755)

    print(f"Wrote {out_path}")
    print(f"Schedule: {weekday_names}, 09:00-22:00 Warsaw, looking back {args.lookback_days} day(s) each run.")
    print()
    print("Review clients/{0}/client-brief.md's Brand Terms / Always Negate / Protected".format(args.slug))
    print("sections once before trusting this on a live account — pmax_brand_generic_audit.py")
    print("reads the brief fresh on every run, so a thin brief means thin judgment every time.")
    print()
    print("Next steps:")
    print(f"  1. Test:    AUDIT_FORCE=1 bash clients/{args.slug}/scripts/run_pmax_brand_generic_audit.sh")
    print(f"  2. Install: python3 scripts/setup_launchd.py --only {args.slug}-pmax-brand-generic-audit")


if __name__ == "__main__":
    main()
